"""Process-local, one-use host identities for native Todo child delegation.

The child execution API accepts an opaque credential and authenticates it
through this trusted host provider.  MCP requests never choose a child actor
or receive the credential.  A child actor subject is generated by this module
and bound to one registered authority, host principal/profile, parent attempt,
logical execution, scope, action set, and idempotency key.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
import secrets
import threading
import time


_PENDING_TTL_SECONDS = 60.0
_MAX_PENDING_CREDENTIALS = 1024
_MAX_BOUND_IDENTITIES = 8192


class ChildCredentialUnavailable(RuntimeError):
    code = "child_credential_issuer_unavailable"


@dataclass(frozen=True, slots=True, repr=False)
class _OpaqueChildCredential:
    token: bytes = field(repr=False)
    project_id: str = field(repr=False)
    binding_digest: str = field(repr=False)

    def __repr__(self) -> str:
        return "<opaque native child credential>"


@dataclass(frozen=True, slots=True)
class _PendingIdentity:
    project_id: str
    subject_id: str
    binding_digest: str
    expires_at: float


class _ProjectAuthenticator:
    def __init__(self, issuer: "NativeChildCredentialIssuer", project_id: str) -> None:
        self._issuer = issuer
        self._project_id = project_id

    @property
    def provider_id(self) -> str:
        return self._issuer.provider_id

    def authenticate(self, credential: object):
        return self._issuer._authenticate(credential, self._project_id)


class NativeChildCredentialIssuer:
    """Mint random child identities and consume their credentials exactly once."""

    provider_id = "project-control.native-child-issuer.v1"

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._pending: dict[bytes, _PendingIdentity] = {}
        self._subjects: dict[str, tuple[str, float]] = {}

    def for_project(self, project_id: str) -> _ProjectAuthenticator:
        return _ProjectAuthenticator(self, _required_text(project_id, "project_id"))

    def issue(
        self,
        *,
        project_id: str,
        principal: str,
        profile: str,
        parent_attempt_id: str,
        execution_id: str,
        logical_id: str,
        scope: object,
        actions: tuple[object, ...],
        idempotency_key: str,
    ) -> _OpaqueChildCredential:
        """Create an opaque one-use credential for one exact host request."""
        project_id = _required_text(project_id, "project_id")
        principal = _required_text(principal, "principal")
        profile = _required_text(profile, "profile")
        parent_attempt_id = _required_text(parent_attempt_id, "parent_attempt_id")
        execution_id = _required_text(execution_id, "execution_id")
        logical_id = _required_text(logical_id, "logical_id")
        idempotency_key = _required_text(idempotency_key, "idempotency_key")
        paths = _scope_rows(getattr(scope, "paths", None), "paths")
        locks = _scope_rows(getattr(scope, "locks", None), "locks")
        if not isinstance(actions, tuple) or not actions or len(actions) > 128:
            raise ChildCredentialUnavailable("child action set is invalid")
        action_ids = tuple(_required_text(action, "action") for action in actions)
        if len(set(action_ids)) != len(action_ids):
            raise ChildCredentialUnavailable("child action set is not unique")

        binding = {
            "project_id": project_id,
            "principal": principal,
            "profile": profile,
            "parent_attempt_id": parent_attempt_id,
            "execution_id": execution_id,
            "logical_id": logical_id,
            "scope": {"paths": paths, "locks": locks},
            "actions": action_ids,
            "idempotency_key": idempotency_key,
        }
        binding_digest = hashlib.sha256(
            json.dumps(binding, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
        ).hexdigest()
        now = time.monotonic()
        token = secrets.token_bytes(32)
        token_digest = hashlib.sha256(token).digest()
        with self._lock:
            self._prune(now)
            if len(self._pending) >= _MAX_PENDING_CREDENTIALS:
                raise ChildCredentialUnavailable("too many pending child credentials")
            retained = self._subjects.get(binding_digest)
            if retained is None or retained[1] <= now:
                subject_id = "pc-child-" + secrets.token_hex(24)
                if len(self._subjects) >= _MAX_BOUND_IDENTITIES:
                    oldest = min(self._subjects, key=lambda key: self._subjects[key][1])
                    self._subjects.pop(oldest, None)
                self._subjects[binding_digest] = (subject_id, now + 24 * 60 * 60)
            else:
                subject_id = retained[0]
            self._pending[token_digest] = _PendingIdentity(
                project_id, subject_id, binding_digest, now + _PENDING_TTL_SECONDS,
            )
        return _OpaqueChildCredential(token, project_id, binding_digest)

    def _authenticate(self, credential: object, expected_project_id: str):
        if not isinstance(credential, _OpaqueChildCredential):
            return None
        token_digest = hashlib.sha256(credential.token).digest()
        now = time.monotonic()
        with self._lock:
            pending = self._pending.pop(token_digest, None)
        if (pending is None or pending.expires_at <= now
                or pending.project_id != expected_project_id
                or credential.project_id != expected_project_id
                or pending.binding_digest != credential.binding_digest):
            return None
        try:
            from todo_orchestrator.api import AuthenticatedPrincipal
            from todo_orchestrator.contracts import ActorKind
        except Exception as error:  # pragma: no cover - runtime binding reports import failures
            raise ChildCredentialUnavailable("native Todo principal contracts are unavailable") from error
        return AuthenticatedPrincipal(
            subject_id=pending.subject_id,
            kind=ActorKind.AUTOMATION,
            label="Project Control delegated child",
        )

    def _prune(self, now: float) -> None:
        self._pending = {key: value for key, value in self._pending.items()
                         if value.expires_at > now}
        self._subjects = {key: value for key, value in self._subjects.items()
                          if value[1] > now}


def _required_text(value: object, field_name: str, *, limit: int = 512) -> str:
    if not isinstance(value, str) or not value.strip() or value != value.strip():
        raise ChildCredentialUnavailable(f"{field_name} is invalid")
    if len(value.encode("utf-8")) > limit:
        raise ChildCredentialUnavailable(f"{field_name} is too long")
    return value


def _scope_rows(value: object, label: str) -> tuple[tuple[str, str], ...]:
    if not isinstance(value, tuple) or len(value) > 4096:
        raise ChildCredentialUnavailable(f"child {label} are invalid")
    rows = []
    for item in value:
        if not isinstance(item, tuple) or len(item) != 2:
            raise ChildCredentialUnavailable(f"child {label} are invalid")
        rows.append((_required_text(item[0], label), _required_text(item[1], label, limit=32)))
    return tuple(rows)


__all__ = ["ChildCredentialUnavailable", "NativeChildCredentialIssuer"]
